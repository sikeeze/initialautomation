"""Logging setup: console + structured status report untuk monitoring.

Tidak pernah menulis token/credential ke log.
"""

from __future__ import annotations

import logging
import os
import re
from datetime import datetime, timezone
from typing import Dict, List, Pattern

SENSITIVE_PATTERNS: List[Pattern] = [
    re.compile(r"(ghp_[A-Za-z0-9]{20,})"),
    re.compile(r"(gho_[A-Za-z0-9]{20,})"),
    re.compile(r"(ghs_[A-Za-z0-9]{20,})"),
    re.compile(r"(github_pat_[A-Za-z0-9_]{20,})"),
    re.compile(r"(Bearer\s+[A-Za-z0-9_\-\.]{20,})"),
]
REDACTED = "***REDACTED***"


def redact_secrets(message: str) -> str:
    """Ganti pola token dengan ***REDACTED***."""
    for pattern in SENSITIVE_PATTERNS:
        message = pattern.sub(REDACTED, message)
    return message


class RedactingFormatter(logging.Formatter):
    """Formatter yang menyensor token sebelum teks sampai ke output."""

    def format(self, record: logging.LogRecord) -> str:
        record.msg = redact_secrets(str(record.msg))
        if record.args:
            record.args = tuple(
                redact_secrets(arg) if isinstance(arg, str) else arg
                for arg in (
                    record.args
                    if isinstance(record.args, tuple)
                    else (record.args,)
                )
            )
        return super().format(record)


class StatusReport:
    """Akumulator ringkasan eksekusi (requirement monitoring)."""

    def __init__(self) -> None:
        self.started_at = datetime.now(timezone.utc)
        self.finished_at: datetime | None = None
        self.success = False
        self.repository = os.getenv("GITHUB_REPOSITORY", "unknown")
        self.branch = os.getenv("INPUT_BRANCH", "main")
        self.commit_sha: str | None = None
        self.commit_message: str | None = None
        self.files_changed: int = 0
        self.insertions = 0
        self.deletions = 0
        self.tasks: List[Dict[str, str]] = []
        self.errors: List[str] = []

    def add_task(self, name: str, status: str, detail: str = "") -> None:
        self.tasks.append(
            {"name": name, "status": status, "detail": redact_secrets(detail)}
        )

    def add_error(self, message: str) -> None:
        self.errors.append(redact_secrets(message))

    def to_markdown(self) -> str:
        """Ubah ringkasan menjadi MAINTENANCE_REPORT.md."""
        self.finished_at = datetime.now(timezone.utc)
        duration = (
            self.finished_at - self.started_at
        ).total_seconds()
        lines = [
            "# Daily Automation Maintenance Report",
            "",
            f"- **Repository**: `{self.repository}`",
            f"- **Branch**: `{self.branch}`",
            f"- **Started (UTC)**: {self.started_at.isoformat(timespec='seconds')}",
            f"- **Finished (UTC)**: {self.finished_at.isoformat(timespec='seconds')}",
            f"- **Duration**: {duration:.1f}s",
            f"- **Status**: {'SUCCESS' if self.success else 'FAILURE'}",
            "",
            "## Maintenance Tasks",
            "",
            "| Task | Status | Detail |",
            "|---|---|---|",
        ]
        for task in self.tasks:
            lines.append(
                f"| {task['name']} | {task['status']} | {task['detail']} |"
            )
        lines += [
            "",
            "## Commit",
            "",
        ]
        if self.commit_sha:
            lines += [
                f"- **SHA**: `{self.commit_sha}`",
                f"- **Message**: `{self.commit_message}`",
                f"- **Files changed**: {self.files_changed}",
                f"- **Insertions**: +{self.insertions}",
                f"- **Deletions**: -{self.deletions}",
            ]
        else:
            lines.append(
                "- No commit was made (tidak ada perubahan nyata "
                "yang diperlukan)."
            )
        if self.errors:
            lines += ["", "## Errors", ""]
            lines += [f"- {err}" for err in self.errors]
        lines += ["", "---", "_Generated by GitHub Daily Automation Bot._", ""]
        return "\n".join(lines)

    def to_github_summary(self) -> str:
        """Ringkasan pendkat untuk $GITHUB_STEP_SUMMARY."""
        self.finished_at = datetime.now(timezone.utc)
        status = "SUCCESS" if self.success else "FAILURE"
        lines = [
            f"## Daily Automation — {status}",
            "",
            f"- Repository: `{self.repository}`",
            f"- Branch: `{self.branch}`",
            f"- Status: **{status}**",
        ]
        if self.commit_sha:
            lines.append(f"- Commit: `{self.commit_sha}`")
            lines.append(f"- Files changed: {self.files_changed}")
        else:
            lines.append("- No commit (no real changes needed).")
        if self.tasks:
            lines += ["", "| Task | Status |", "|---|---|"]
            for task in self.tasks:
                lines.append(
                    f"| {task['name']} | {task['status']} |"
                )
        if self.errors:
            lines += ["", "**Errors:**"]
            lines += [f"- {err}" for err in self.errors]
        return "\n".join(lines)


def setup_logging(level: str = "INFO") -> logging.Logger:
    """Konfigurasi root logger dengan RedactingFormatter."""
    numeric = getattr(logging, level.upper(), logging.INFO)
    root = logging.getLogger()
    root.setLevel(numeric)
    # Bersihkan handler yang sudah ada agar tidak dobel output
    for handler in list(root.handlers):
        root.removeHandler(handler)
    handler = logging.StreamHandler()
    handler.setFormatter(
        RedactingFormatter(
            fmt="%(asctime)s | %(levelname)-8s | %(name)s | %(message)s",
            datefmt="%Y-%m-%d %H:%M:%S",
        )
    )
    root.addHandler(handler)
    return logging.getLogger("bot")


def write_step_summary(report: StatusReport) -> None:
    """Tulis ringkasan ke $GITHUB_STEP_SUMMARY bila ada."""
    path = os.getenv("GITHUB_STEP_SUMMARY")
    if path:
        try:
            with open(path, "w", encoding="utf-8") as fh:
                fh.write(report.to_github_summary())
        except OSError as exc:
            logging.getLogger("bot").warning(
                "Tidak bisa menulis step summary: %s", exc
            )
